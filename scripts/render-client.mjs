/**
 * Renders the `client.js` payload from the plain-JS plugin body.
 *
 * The body is the module function body (it returns a Cordis Plugin). The
 * wrapper supplies the web module loader's handoff format: the factory receives
 * the loader's `require`, binds React from the platform module table, provides
 * the `styles.insert` shim the body calls, and captures the body's returned
 * plugin object as `module.exports`.
 *
 * `build-client.mjs` writes the result and the drift test re-renders it, so the
 * committed bundle and the source body cannot disagree silently.
 */
export function renderClient(body, id) {
  return `/* Generated by scripts/build-client.mjs from client.body.js — do not edit. */
window.__ModuleLoader__.load({ id: ${JSON.stringify(id)}, factory: (require) => {
  var module = { exports: {} }; var exports = module.exports;
  const React = require('react');
  const styles = {
    insert: (css) => {
      if (typeof document === 'undefined') return;
      const tag = document.createElement('style');
      tag.dataset.plugin = ${JSON.stringify(id)};
      tag.textContent = css;
      document.head.appendChild(tag);
    },
  };
  module.exports = (() => {
${body}
  })();
  return module.exports;
} });
`
}
